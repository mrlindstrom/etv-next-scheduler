// Writes src/server/library-schema.ts: the tables and indexes of an empty
// library.sqlite, so a new install can start a library without an ErsatzTV
// legacy database to import. Takes the same tables the import copies
// (includeTable), from an existing library or legacy database:
//
//   npm run build && node scripts/gen-library-schema.mjs [data/library.sqlite]
//
// Run it again only if the import's table list changes.
import { DatabaseSync } from "node:sqlite";
import { writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { includeTable } from "../dist/server/library-import.js";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const src = process.argv[2] ?? join(root, "data", "library.sqlite");
const db = new DatabaseSync(src, { readOnly: true });
const rows = db.prepare("SELECT type, name, tbl_name, sql FROM sqlite_master WHERE sql IS NOT NULL AND type IN ('table', 'index') ORDER BY type DESC, name").all();
db.close();

const stmts = [];
for (const r of rows) {
  if (!includeTable(r.tbl_name)) continue;
  // as the import does: the same file can be in several libraries
  const sql = r.name === "IX_MediaFile_PathHash" ? String(r.sql).replace(/UNIQUE\s+/i, "") : String(r.sql);
  stmts.push(sql.replace(/\r\n?/g, "\n"));
}
const tables = rows.filter((r) => r.type === "table" && includeTable(r.tbl_name)).length;

const out = `// Generated by scripts/gen-library-schema.mjs; don't edit by hand.
// The tables (${tables}) and indexes (${stmts.length - tables}) of an empty library.sqlite: the
// ErsatzTV legacy media-library tables the import copies (includeTable).
export const LIBRARY_SCHEMA: readonly string[] = [
${stmts.map((s) => `  ${JSON.stringify(s)},`).join("\n")}
];
`;
writeFileSync(join(root, "src", "server", "library-schema.ts"), out);
console.log(`wrote src/server/library-schema.ts: ${tables} tables, ${stmts.length - tables} indexes`);
